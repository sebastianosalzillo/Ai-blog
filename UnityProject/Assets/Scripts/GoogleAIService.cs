    // --- Request Structures for Google Gemini API ---
    // These classes are designed to match the JSON structure expected by the Gemini API.
    // See Google AI Gemini API documentation for more details on request/response formats.

    /// <summary>
    /// Represents a part of the content in a Gemini API request.
    /// Typically contains text.
    /// </summary>
    [System.Serializable]
    public class GeminiRequestPart
    {
        /// <summary>The text content of this part.</summary>
        public string text;
    }

    /// <summary>
    /// Represents the content array in a Gemini API request, containing one or more parts.
    /// </summary>
    [System.Serializable]
    public class GeminiRequestContent
    {
        /// <summary>Array of parts that make up this content.</summary>
        public GeminiRequestPart[] parts;
    }

    /// <summary>
    /// Represents the top-level request payload for the Gemini API.
    /// </summary>
    [System.Serializable]
    public class GeminiRequest
    {
        /// <summary>Array of content blocks sent to the model.</summary>
        public GeminiRequestContent[] contents;
        // Note: For more advanced scenarios, you might add 'tools' or 'generationConfig' here.
    }

    // --- Response Structures for Google Gemini API ---

    /// <summary>
    /// Represents a part of the content in a Gemini API response.
    /// Typically contains the generated text.
    /// </summary>
    [System.Serializable]
    public class GeminiResponsePart
    {
        /// <summary>The text content of this part.</summary>
        public string text;
        // Potentially other fields like "functionCall" could be added here if using function calling.
    }

    /// <summary>
    /// Represents the content in a Gemini API response candidate.
    /// </summary>
    [System.Serializable]
    public class GeminiResponseContent
    {
        /// <summary>Array of parts received from the model.</summary>
        public GeminiResponsePart[] parts;
        /// <summary>The role of the entity that provided the content (e.g., "model").</summary>
        public string role;
    }

    /// <summary>
    /// Represents a candidate generated by the Gemini API.
    /// </summary>
    [System.Serializable]
    public class GeminiResponseCandidate
    {
        /// <summary>The content generated by the model for this candidate.</summary>
        public GeminiResponseContent content;
        // Other fields like "finishReason", "index", "safetyRatings" can be added here
        // if they are needed for your application logic.
    }

    /// <summary>
    /// Represents the top-level response from the Gemini API.
    /// </summary>
    [System.Serializable]
    public class GeminiResponse
    {
        /// <summary>Array of candidates generated by the model.</summary>
        public GeminiResponseCandidate[] candidates;
        // "promptFeedback" can be added here if you need to inspect prompt safety ratings etc.
    }

    /// <summary>
    /// Service class for interacting with the Google Gemini AI API.
    /// Handles sending requests and parsing responses.
    /// This component should be attached to a GameObject in the scene.
    /// </summary>
    public class GoogleAIService : MonoBehaviour
    {
        [Header("API Configuration")]
        [Tooltip("Google AI API Key. This key can be overridden by the apiKeyOverride parameter in GenerateTextAsync. " +
                 "It's recommended to set this via ShopkeeperAI or another manager rather than directly here if multiple AI instances exist.")]
        public string apiKey; 

        private const string DEFAULT_MODEL_NAME = "gemini-1.5-flash"; // Default model to use if not specified.

        /// <summary>
        /// Generates text content using the Google Gemini API.
        /// </summary>
        /// <param name="userPrompt">The prompt to send to the AI.</param>
        /// <param name="modelNameOverride">Optional: Specific model name to use (e.g., "gemini-pro"). If null or empty, uses DEFAULT_MODEL_NAME.</param>
        /// <param name="apiKeyOverride">Optional: API key to use for this specific request. If null or empty, uses the public apiKey field of this component.</param>
        /// <returns>The generated text from the AI's first candidate, or null if an error occurred or no text was generated.</returns>
        public async Task<string> GenerateTextAsync(string userPrompt, string modelNameOverride = null, string apiKeyOverride = null)
        {
            // Determine which API key and model name to use for this request.
            string currentApiKey = string.IsNullOrEmpty(apiKeyOverride) ? this.apiKey : apiKeyOverride;
            string currentModelName = string.IsNullOrEmpty(modelNameOverride) ? DEFAULT_MODEL_NAME : modelNameOverride;

            // Validate API key.
            if (string.IsNullOrEmpty(currentApiKey))
            {
                Debug.LogError("[GoogleAIService] API Key is missing. Please provide it in the component's inspector or pass it as an argument to GenerateTextAsync.");
                return null;
            }

            // Validate user prompt.
            if (string.IsNullOrEmpty(userPrompt))
            {
                Debug.LogError("[GoogleAIService] Prompt cannot be empty.");
                return null;
            }

            // Construct the API URL.
            // The `v1beta` endpoint is used here; this might change with API versions.
            string apiUrl = $"https://generativelanguage.googleapis.com/v1beta/models/{currentModelName}:generateContent?key={currentApiKey}";

            // Construct the JSON payload for the API request.
            GeminiRequest requestPayload = new GeminiRequest
            {
                contents = new GeminiRequestContent[] // The 'contents' array typically holds the conversation history or multi-turn context.
                {
                    new GeminiRequestContent
                    {
                        parts = new GeminiRequestPart[] // Each content entry can have multiple parts (e.g., text and images).
                        {
                            new GeminiRequestPart { text = userPrompt }
                        }
                    }
                }
            };
            string jsonPayload = JsonUtility.ToJson(requestPayload);
            byte[] bodyRaw = Encoding.UTF8.GetBytes(jsonPayload); // Convert JSON string to byte array.

            // Create and configure the UnityWebRequest.
            using (UnityWebRequest request = new UnityWebRequest(apiUrl, "POST"))
            {
                request.uploadHandler = new UploadHandlerRaw(bodyRaw); // Set the request body.
                request.downloadHandler = new DownloadHandlerBuffer(); // Buffer to receive the response.
                request.SetRequestHeader("Content-Type", "application/json"); // Specify JSON content type.

                Debug.Log($"[GoogleAIService] Sending request to Gemini API (Model: {currentModelName}). Prompt (first 50 chars): \"{userPrompt.Substring(0, Mathf.Min(userPrompt.Length, 50))}...\"");

                // Asynchronously send the request and wait for it to complete.
                var asyncOp = request.SendWebRequest();
                while (!asyncOp.isDone)
                {
                    await Task.Yield(); // Yield control to allow Unity's main thread to continue processing other tasks.
                }

                // Check for network or HTTP errors.
#if UNITY_2020_1_OR_NEWER // Newer Unity versions use 'result'
                if (request.result == UnityWebRequest.Result.ConnectionError ||
                    request.result == UnityWebRequest.Result.ProtocolError ||
                    request.result == UnityWebRequest.Result.DataProcessingError)
                {
                    Debug.LogError($"[GoogleAIService] Error calling Gemini API: {request.error}\nResponse Code: {request.responseCode}\nResponse Body: {request.downloadHandler.text}");
                    return null;
                }
#else // Older Unity versions use 'isNetworkError' or 'isHttpError'
                if (request.isNetworkError || request.isHttpError)
                {
                    Debug.LogError($"[GoogleAIService] Error calling Gemini API: {request.error}\nResponse Code: {request.responseCode}\nResponse Body: {request.downloadHandler.text}");
                    return null;
                }
#endif
                else // Request was successful.
                {
                    string responseJson = request.downloadHandler.text;
                    Debug.Log($"[GoogleAIService] Gemini API Raw Response: {responseJson}");

                    try
                    {
                        // Attempt to parse the JSON response.
                        GeminiResponse response = JsonUtility.FromJson<GeminiResponse>(responseJson);

                        // Check if the response contains valid candidates and text.
                        if (response != null && response.candidates != null && response.candidates.Length > 0)
                        {
                            GeminiResponseCandidate firstCandidate = response.candidates[0];
                            if (firstCandidate.content != null && firstCandidate.content.parts != null && firstCandidate.content.parts.Length > 0)
                            {
                                string generatedText = firstCandidate.content.parts[0].text;
                                Debug.Log($"[GoogleAIService] Gemini API Generated Text: {generatedText}");
                                return generatedText; // Successfully extracted text.
                            }
                            else
                            {
                                Debug.LogError("[GoogleAIService] Gemini API Response: No text parts found in the first candidate's content.");
                                return null;
                            }
                        }
                        // Handle cases where JsonUtility.FromJson might return null for a malformed JSON that still contains an error message from the API.
                        else if (responseJson.ToLower().Contains("error")) 
                        {
                             Debug.LogError($"[GoogleAIService] Gemini API returned an error in the JSON payload: {responseJson}");
                             return null;
                        }
                        else
                        {
                            Debug.LogError("[GoogleAIService] Gemini API Response: No candidates found or response format is unexpected.");
                            return null;
                        }
                    }
                    catch (System.Exception ex) // Catch errors during JSON parsing.
                    {
                        Debug.LogError($"[GoogleAIService] Error parsing Gemini API JSON response: {ex.Message}\nRaw Response: {responseJson}");
                        return null;
                    }
                }
            }
        }

